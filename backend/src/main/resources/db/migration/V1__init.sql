-- Un incident = une panne sur un namespace, avec le diagnostic de l'agent et la décision humaine
CREATE TABLE incident (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace          VARCHAR(253) NOT NULL,
    alert_names        TEXT NOT NULL,
    severity           VARCHAR(30),
    summary            TEXT,
    status             VARCHAR(30) NOT NULL,
    category           VARCHAR(30),
    root_cause         TEXT,
    confidence         DOUBLE PRECISION,
    diagnosis_json     TEXT,
    remediation_action VARCHAR(30),
    remediation_json   TEXT,
    tool_calls         INTEGER,
    duration_seconds   DOUBLE PRECISION,
    action_result      TEXT,
    error_message      TEXT,
    decided_by         VARCHAR(100),
    decided_at         TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_incident_namespace_status ON incident (namespace, status);

-- Chaque outil appelé par l'agent pendant l'enquête (le « raisonnement » affiché dans le dashboard)
CREATE TABLE agent_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incident (id) ON DELETE CASCADE,
    step_order  INTEGER NOT NULL,
    node        VARCHAR(50) NOT NULL,
    tool        VARCHAR(100),
    args_json   TEXT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_agent_step_incident ON agent_step (incident_id, step_order);
